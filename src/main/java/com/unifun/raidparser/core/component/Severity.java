package com.unifun.raidparser.core.component;

/**
 * Классификация статуса для потребителей API: по ней клиент решает,
 * что показать красным, а что нет, не зная внутренних значений вендоров.
 * <p>
 * Порядок объявления — это порядок вывода, от худшего к лучшему.
 */
public enum Severity {
    /** Требует немедленного вмешательства: отказ диска, БП или батареи. */
    CRITICAL,
    /** Работает, но с оговорками: предсказанный отказ, потеря резервирования, зарядка. */
    WARNING,
    /** Данных нет или их не удалось разобрать — не то же самое, что «всё хорошо». */
    NO_DATA,
    /** Всё в порядке. */
    OK
}
